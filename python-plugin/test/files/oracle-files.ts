/** The oracle text with Ferrule's branding substitutions applied: what the emitters must match. */
export function brand(path: string, text: string): string {
  let out = text;
  for (const b of BRANDING)
    if (b.file === path || b.file === '*') out = out.replaceAll(b.oracle, b.ferrule);
  return out;
}
