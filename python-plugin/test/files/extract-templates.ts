/**
 * Regenerates `src/emit/files/templates/*.ts` from the pinned OneBusAway oracle checkout.
 *
 * Run: `node python-plugin/test/files/extract-templates.ts` after `python3 oracles/fetch.py
 * onebusaway`. Every per-SDK value of the oracle is replaced by a `%%TOKEN%%` (see
 * `src/emit/files/render.ts`) and every branding line by its Ferrule text (BRANDING.md). The
 * output is reviewed like golden files: a human approves template diffs.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brand, DROPPED_FILES, TEMPLATE_FILES } from './oracle-files.ts';

const here = dirname(fileURLToPath(import.meta.url));
const oracle = join(here, '../../../oracles/cache/onebusaway-python');
const outDir = join(here, '../../src/emit/files/templates');

/**
 * Each template is derived from the Apache-2.0 OneBusAway SDK (Stainless-generated) and says so,
 * per the licensing rules in CLAUDE.md.
 */
const HEADER = (path: string): string =>
  `// Derived from ${path} of OneBusAway/python-sdk@4c20fa834c2a (Apache-2.0).\n` +
  '// Modified by The Ferrule Authors: per-SDK values replaced by %%TOKENS%%, branding per\n' +
  '// BRANDING.md. Generated by test/files/extract-templates.ts; do not edit.\n';

type Rule = readonly [string | RegExp, string];

/** Values of the oracle, most specific first so shorter ones don't eat longer ones. */
const COMMON: readonly Rule[] = [
  ['OneBusAway/python-sdk', '%%REPO%%'],
  ['ONEBUSAWAY_SDK', '%%ENV_PREFIX%%'],
  ['ONEBUSAWAY_API_KEY', '%%API_KEY_ENV%%'],
  ['OnebusawaySDK', '%%CLIENT%%'],
  ['Onebusaway SDK', '%%ORG_TITLE%%'],
  ['OneBusAway SDK', '%%README_TITLE%%'],
  ['onebusaway-sdk', '%%ORG_NAME%%'],
  ['https://developer.onebusaway.org', '%%DOCS_URL%%'],
  ['developer.onebusaway.org', '%%DOCS_LABEL%%'],
  ['info@onebusaway.org', '%%CONTACT%%'],
];

const PER_FILE: Readonly<Record<string, readonly Rule[]>> = {
  'pyproject.toml': [
    ['name = "onebusaway"', 'name = "%%DIST%%"'],
    ['version = "1.30.0"', 'version = "%%VERSION%%"'],
  ],
  '.release-please-manifest.json': [['1.30.0', '%%VERSION%%']],
  LICENSE: [['Copyright 2026', 'Copyright %%YEAR%%']],
  'requirements.lock': [[/# via onebusaway$/gm, '# via %%DIST%%']],
  'requirements-dev.lock': [[/# via onebusaway$/gm, '# via %%DIST%%']],
  'README.md': [
    [/pip install onebusaway/g, 'pip install %%DIST%%'],
    ['pypi/v/onebusaway.svg', 'pypi/v/%%DIST%%.svg'],
    ['project/onebusaway/', 'project/%%DIST%%/'],
    [/current_time = /g, '%%EX_RESULT%% = '],
    [
      /current_time\.(with_raw_response\.|with_streaming_response\.|)retrieve\(\)/g,
      '%%EX_ACCESSOR%%.$1%%EX_METHOD%%(%%EX_ARGS%%)',
    ],
    [/`current_time\.retrieve\(\)`/g, '`%%EX_ACCESSOR%%.%%EX_METHOD%%()`'],
    ['print(current_time)', 'print(%%EX_RESULT%%)'],
  ],
  'scripts/mock': [
    [/array-format=repeat/g, 'array-format=%%ARRAY_FORMAT%%'],
    [/object-format=brackets/g, 'object-format=%%OBJECT_FORMAT%%'],
  ],
  'scripts/test': [
    [/array-format=repeat/g, 'array-format=%%ARRAY_FORMAT%%'],
    [/object-format=brackets/g, 'object-format=%%OBJECT_FORMAT%%'],
  ],
  'tests/test_client.py': [
    [/"key": /g, '"%%AUTH_QUERY%%": '],
    [/([?&])key=/g, '$1%%AUTH_QUERY%%='],
    ["Include the 'key' in", "Include the '%%AUTH_QUERY%%' in"],
    [
      /respx_mock\.get\("\/api\/where\/current-time\.json"\)/g,
      'respx_mock.%%PROBE_VERB%%("%%PROBE_PATH%%")',
    ],
    [
      /current_time\.(with_raw_response|with_streaming_response)\.retrieve\(\)/g,
      '%%PROBE_ACCESSOR%%.$1.%%PROBE_METHOD%%(%%PROBE_ARGS%%)',
    ],
    [
      /current_time\.with_raw_response\.retrieve\(/g,
      '%%PROBE_ACCESSOR%%.with_raw_response.%%PROBE_METHOD%%(%%PROBE_ARGS_COMMA%%',
    ],
  ],
};

function apply(text: string, rules: readonly Rule[]): string {
  let out = text;
  for (const [from, to] of rules) {
    out = typeof from === 'string' ? out.replaceAll(from, to) : out.replace(from, to);
  }
  return out;
}

/** Lines that import the client class are re-sorted at render time (ruff isort length-sort). */
function markSortedImports(path: string, text: string): string {
  if (!path.endsWith('.py')) return text;
  return text.replace(/^from \S+ import [^(\n]*%%CLIENT%%[^\n]*$/gm, (line) => `%%isort%%${line}`);
}

export function templatize(path: string, raw: string): string {
  let text = apply(brand(path, raw), PER_FILE[path] ?? []);
  text = apply(text, COMMON);
  text = text.replace(/\bonebusaway\b/g, '%%PACKAGE%%');
  return markSortedImports(path, text);
}

function moduleName(path: string): string {
  return path.replace(/^\./, 'dot_').replace(/[^A-Za-z0-9]+/g, '_');
}

function literal(text: string): string {
  return `\`${text.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${')}\``;
}

function main(): void {
  mkdirSync(outDir, { recursive: true });
  for (const path of TEMPLATE_FILES) {
    if (DROPPED_FILES.includes(path)) continue;
    const text = templatize(path, readFileSync(join(oracle, path), 'utf8'));
    const mod = moduleName(path);
    writeFileSync(join(outDir, `${mod}.ts`), `${HEADER(path)}export default ${literal(text)};\n`);
  }
  const imports = TEMPLATE_FILES.filter((p) => !DROPPED_FILES.includes(p)).map(
    (p) => `import ${moduleName(p)} from './${moduleName(p)}.ts';`,
  );
  const entries = TEMPLATE_FILES.filter((p) => !DROPPED_FILES.includes(p)).map(
    (p) => `  [${JSON.stringify(p)}, ${moduleName(p)}],`,
  );
  writeFileSync(
    join(outDir, 'index.ts'),
    [
      '// Generated by test/files/extract-templates.ts. Do not edit.',
      ...imports,
      '',
      '/** Output path -> template text (tokens per render.ts). */',
      'export const TEMPLATES: ReadonlyMap<string, string> = new Map([',
      ...entries,
      ']);',
      '',
    ].join('\n'),
  );
  // Leave the tree as biome formats it, so a re-run on an unchanged oracle is a no-op.
  execFileSync('pnpm', ['exec', 'biome', 'check', '--write', outDir], { stdio: 'inherit' });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
