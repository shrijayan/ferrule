# Push the merged regeneration (branch ferrule/regenerate, or a conflict branch, checked out by
# regenerate.sh) and the generated branch, and create or update the PR with the semver label.
# With DRY_RUN=1 it prints the plan and touches neither git nor the network.
#
# Env: LABEL (major|minor|patch), BREAKING, ADDITIVE, WORKSPACE, GH_TOKEN, DRY_RUN,
# CHANGED (true when there is a new generation), CONFLICT (true for a merge conflict),
# GITHUB_REPOSITORY_OWNER.
set -euo pipefail

BRANCH="ferrule/regenerate"
: "${LABEL:?}" "${BREAKING:?}" "${ADDITIVE:?}" "${WORKSPACE:?}"
[[ "$LABEL" =~ ^(major|minor|patch)$ ]] || { echo "::error::bad label $LABEL" >&2; exit 1; }

title="chore: regenerate SDK (${LABEL})"
conflict_note=""
if [[ "${CONFLICT:-false}" == "true" ]]; then
  title="chore: regenerate SDK (merge conflict)"
  conflict_note="

The new generation conflicts with custom code: resolve the conflict markers on this branch."
fi
body="Regenerated by the Ferrule action, merged three-way with the custom code on this branch.

| | count |
|---|---|
| breaking | ${BREAKING} |
| additive | ${ADDITIVE} |

Semver label: \`${LABEL}\`. Breaking changes fail the check unless the PR carries \`ferrule:allow-breaking\`.
Keep the \`Ferrule-Generated-From\` trailer when merging: the next regeneration merges from it.${conflict_note}"

run() {
  if [[ "${DRY_RUN:-0}" == "1" ]]; then
    printf '+'; printf ' %q' "$@"; printf '\n'
  else
    "$@"
  fi
}

# Same-repo PRs only: a fork can open a PR whose head branch is also named $BRANCH.
# shellcheck disable=SC2016 # jq, not the shell, expands $ENV
SAME_REPO_JQ='[.[] | select(.isCrossRepository == false and .headRepositoryOwner.login == $ENV.GITHUB_REPOSITORY_OWNER)][0].number // empty'

if [[ "${DRY_RUN:-0}" != "1" ]]; then
  : "${GITHUB_REPOSITORY_OWNER:?}"
  if [[ "${CHANGED:-false}" != "true" ]]; then
    echo "no new generation; nothing to open"
    exit 0
  fi
  cd "$WORKSPACE"
  gh auth setup-git
fi

run git push --force origin "HEAD:refs/heads/$BRANCH"
run git push --force origin "refs/heads/generated:refs/heads/generated"
run gh label create "$LABEL" --force --color ededed --description "Ferrule semver bump"
existing=""
if [[ "${DRY_RUN:-0}" != "1" ]]; then
  existing="$(gh pr list --head "$BRANCH" --state open \
    --json number,isCrossRepository,headRepositoryOwner --jq "$SAME_REPO_JQ")"
fi
if [[ -n "$existing" ]]; then
  # New content was force-pushed: an earlier breaking-change approval no longer applies.
  run gh pr edit "$existing" --title "$title" --body "$body" \
    --remove-label major,minor,patch,ferrule:allow-breaking --add-label "$LABEL"
else
  run gh pr create --head "$BRANCH" --title "$title" --body "$body" --label "$LABEL"
fi
