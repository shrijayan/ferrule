"""Build ``site/src/data/corpus.json`` from ``reports/corpus/*.json`` (scripts/corpus/run.py).

One row per Tier 1 spec, in manifest order, with every stage's status, the scale of the spec
and of the generated SDK, determinism, the comparison with an official SDK when there is one,
and the Forge gaps (docs/forge-gaps.md) the run hit. Output is deterministic: the only date is
``--date`` (the run date), never the clock; a spec without a report is listed as not run.

Usage: python -m scripts.board.corpus --date YYYY-MM-DD [--reports DIR] [--manifest FILE]
                                      [--gaps FILE] [--generator TEXT] [--out FILE]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import cast

from corpus.fetch import Spec, parse_manifest
from scripts.corpus.harness import STAGES, failed_at, reached

ROOT = Path(__file__).resolve().parents[2]
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
DETAIL = 300

# Why a spec has no official Stainless-generated Python SDK to compare with: checked on the run
# date by looking for Stainless's .stats.yml in the official SDK repository.
NO_COMPARE = {
    "stripe": "stripe/stripe-python is generated by Stripe's own generator, not Stainless.",
    "github": "GitHub publishes no official Python SDK.",
    "kubernetes": "kubernetes-client/python is generated with OpenAPI Generator.",
    "twilio": "twilio/twilio-python is generated by Twilio's own generator.",
    "azure-storage": "azure-mgmt-storage is generated with AutoRest/TypeSpec.",
    "slack": "slackapi/python-slack-sdk is written by hand.",
    "plaid": "plaid/plaid-python is generated with OpenAPI Generator.",
    "square": "square/square-python-sdk is generated with Fern.",
    "discord": "Discord publishes no official Python SDK.",
    "docker": "docker/docker-py is written by hand.",
    "jira": "Atlassian publishes no official Python SDK for Jira Cloud.",
}

# Gaps a run hits, by the FER code a workaround reports or by text in the failing stage.
GAP_CODES = {
    "FER1601": "G22",
    "FER1602": "G23",
    "FER1610": "G24",
    "FER1603": "G25",
    "FER1604": "G26",
    "FER1605": "G26",
    "FER1606": "G27",
    "FER1607": "G28",
    "FER1609": "G30",
    "FER1608": "G31",
}
GAP_TEXT = ((re.compile(r"is to another document"), "G29"),)
# Local checkout paths in tool output: dropped, so the data names files relative to the SDK.
_LOCAL_RE = re.compile(r"/\S*?/\.cache/corpus/[^/\s]+/(?:sdk/)?")
_GAP_ROW_RE = re.compile(r"^\| (G\d+) \| ([^|]+) \|", re.MULTILINE)


class CorpusBoardError(Exception):
    """A report is missing a field or has the wrong type."""


def _obj(raw: object) -> dict[str, object]:
    return cast("dict[str, object]", raw) if isinstance(raw, dict) else {}


def _int(raw: object) -> int | None:
    return raw if isinstance(raw, int) and not isinstance(raw, bool) else None


def gap_titles(markdown: str) -> dict[str, str]:
    """Gap id to its "Need" column, from the docs/forge-gaps.md table."""
    return {m[1]: m[2].strip() for m in _GAP_ROW_RE.finditer(markdown)}


def first_line(text: str) -> str:
    """Return the first informative line of a stage error, shortened and without local paths."""
    text = _LOCAL_RE.sub("", text)
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if not lines:
        return ""
    rest = lines[1:]
    cause = next(
        (line for line in rest if "FER" in line or "error" in line), rest[0] if rest else ""
    )
    return f"{lines[0]} {cause}".strip()[:DETAIL]


def stage_rows(stages: dict[str, object]) -> list[dict[str, object]]:
    """Every harness stage in order: pass, fail or not run, with a short detail."""
    rows: list[dict[str, object]] = []
    for name in (*STAGES, "compare"):
        record = _obj(stages.get(name))
        if not record:
            if name != "compare":
                rows.append({"name": name, "status": "not-run"})
            continue
        status = "pass" if record.get("ok") is True else "fail"
        row: dict[str, object] = {"name": name, "status": status}
        error = record.get("error")
        if status == "fail" and isinstance(error, str):
            row["detail"] = first_line(error)
        causes = _obj(record.get("causes"))
        if status == "fail" and causes:
            row["causes"] = {_LOCAL_RE.sub("", k)[:DETAIL]: v for k, v in causes.items()}
        seconds = record.get("seconds")
        if isinstance(seconds, int | float) and not isinstance(seconds, bool):
            row["seconds"] = seconds
        rows.append(row)
    return rows


def gaps_of(report: dict[str, object], titles: dict[str, str]) -> list[dict[str, object]]:
    """Gaps the run hit: worked around (by FER code) or blocking (by the failing stage)."""
    codes = _obj(report.get("fer_codes"))
    found: dict[str, bool] = {}
    for code, gap in GAP_CODES.items():
        if code in codes:
            found.setdefault(gap, False)
    stages = _obj(report.get("stages"))
    stopped = failed_at(report)
    error = str(_obj(stages.get(stopped)).get("error", "")) if stopped else ""
    for pattern, gap in GAP_TEXT:
        if pattern.search(error):
            found[gap] = True
    return [
        {"id": gap, "title": titles.get(gap, ""), "blocking": blocking}
        for gap, blocking in sorted(found.items(), key=lambda kv: int(kv[0][1:]))
    ]


def compare_of(spec: Spec, stages: dict[str, object]) -> dict[str, object]:
    """Return the comparison with the official SDK, or why there is none."""
    if spec.compare is None:
        return {"status": "none", "reason": NO_COMPARE.get(spec.name, "")}
    record = _obj(stages.get("compare"))
    base: dict[str, object] = {
        "repo": spec.compare.repo,
        "sha": spec.compare.sha,
        "package": spec.compare.package,
    }
    if not record:
        return {**base, "status": "not-run"}
    if record.get("ok") is not True:
        return {**base, "status": "fail", "detail": first_line(str(record.get("error", "")))}
    keys = (
        "breaking",
        "additive",
        "closeness",
        "endpoints_official",
        "endpoints_ours",
        "endpoints_shared",
        "endpoints_official_in_spec",
    )
    return {**base, "status": "pass", **{k: record.get(k) for k in keys}}


def build_row(spec: Spec, raw: object, titles: dict[str, str]) -> dict[str, object]:
    """One spec's row; ``raw`` is its report (None when it has not run)."""
    source = {"url": spec.url, "sha256": spec.sha256, "source_sha": spec.source_sha}
    if raw is None:
        return {"name": spec.name, **source, "reached": "none", "failed_at": None, "ran": False}
    report = _obj(raw)
    if report.get("spec") != spec.name:
        msg = f"{spec.name}: report is for {report.get('spec')!r}"
        raise CorpusBoardError(msg)
    stages = _obj(report.get("stages"))
    counts = _obj(report.get("counts"))
    fetch = _obj(stages.get("fetch"))
    convert = _obj(stages.get("convert"))
    render = _obj(stages.get("render"))
    tests = _obj(stages.get("tests"))
    determinism = _obj(stages.get("determinism"))
    checks = {
        t: _int(_obj(stages.get(t)).get("errors"))
        for t in ("ruff", "pyright", "mypy")
        if stages.get(t)
    }
    return {
        "name": spec.name,
        **source,
        "ran": True,
        "format": fetch.get("format"),
        "bytes": fetch.get("bytes"),
        "swagger2": convert.get("swagger2") is True,
        "reached": reached(report),
        "failed_at": failed_at(report),
        "stages": stage_rows(stages),
        "scale": {
            k: counts.get(k)
            for k in (
                "operations",
                "schemas",
                "resources",
                "methods",
                "generated_methods",
                "skipped",
                "files",
            )
        },
        "skipped_by_code": _obj(counts.get("skipped_by_code")),
        "models_added": len(cast("list[object]", report.get("models_added") or [])),
        "convert_codes": _obj(convert.get("codes")),
        "generation_seconds": render.get("seconds"),
        "check_errors": checks,
        "tests": {k: _int(tests.get(k)) for k in ("passed", "failed", "errors", "skipped", "total")}
        if _int(tests.get("total")) is not None
        else None,
        "deterministic": None if not determinism else determinism.get("ok") is True,
        "digest": render.get("digest"),
        "compare": compare_of(spec, stages),
        "gaps": gaps_of(report, titles),
    }


def build(
    specs: list[Spec],
    reports: dict[str, object],
    titles: dict[str, str],
    date: str,
    generator: str | None,
) -> str:
    """Render corpus.json (manifest order, trailing newline)."""
    if not DATE_RE.match(date):
        msg = f"--date must be YYYY-MM-DD, got {date!r}"
        raise CorpusBoardError(msg)
    rows = [build_row(s, reports.get(s.name), titles) for s in specs]
    doc = {"run_date": date, "generator": generator, "tier": 1, "specs": rows}
    return json.dumps(doc, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description="Build the real-world specs board data file.")
    parser.add_argument("--date", required=True, help="the run date (YYYY-MM-DD)")
    parser.add_argument("--reports", type=Path, default=ROOT / "reports" / "corpus")
    parser.add_argument("--manifest", type=Path, default=ROOT / "corpus" / "manifest.yaml")
    parser.add_argument("--gaps", type=Path, default=ROOT / "docs" / "forge-gaps.md")
    parser.add_argument("--generator", help="`ferrule-gen --version` of the run")
    parser.add_argument("--out", type=Path, default=ROOT / "site/src/data/corpus.json")
    args = parser.parse_args(argv)
    manifest = parse_manifest(cast("Path", args.manifest).read_text(encoding="utf-8"))
    reports_dir = cast("Path", args.reports)
    reports: dict[str, object] = {
        p.stem: json.loads(p.read_text(encoding="utf-8"))
        for p in sorted(reports_dir.glob("*.json"))
    }
    titles = gap_titles(cast("Path", args.gaps).read_text(encoding="utf-8"))
    try:
        text = build(
            manifest.tier1,
            reports,
            titles,
            cast("str", args.date),
            cast("str | None", args.generator),
        )
    except CorpusBoardError as exc:
        sys.stderr.write(f"corpus board: {exc}\n")
        return 1
    out = cast("Path", args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    ran = sum(1 for s in manifest.tier1 if s.name in reports)
    sys.stdout.write(f"corpus board: {ran} of {len(manifest.tier1)} specs -> {out}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
