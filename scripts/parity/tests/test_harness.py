from pathlib import Path

import pytest

from oracles.fetch import Oracle
from scripts.parity.harness import (
    HarnessError,
    Outcomes,
    breakage_kinds,
    lock_requirements,
    mock_command,
    parse_junit,
    resolve_pair,
)


def oracle(
    name: str,
    kind: str,
    pairs_with: str | None,
    language: str | None = None,
    paired: str | None = None,
) -> Oracle:
    return Oracle(
        name,
        "acme",
        kind,
        "a/b",
        "https://x",
        "0" * 40,
        "",
        None,
        {},
        pairs_with,
        paired=paired,
        language=language,
    )


ORACLES = [
    oracle("acme-python", "sdk", "acme-config"),
    oracle("acme-config", "config", "acme-python", paired="proven"),
    oracle("lone-config", "config", None),
]
# The same group with SDKs in other languages, as the manifest lists them after the Python one.
MULTI = [
    oracle("acme-config", "config", "acme-python", paired="proven"),
    oracle("acme-python", "sdk", "acme-config", "python"),
    oracle("acme-typescript", "sdk", "acme-config", "typescript", "nearest"),
    oracle("acme-go", "sdk", "acme-config", "go", "proven"),
]


@pytest.mark.parametrize("oracles", [ORACLES, MULTI])
@pytest.mark.parametrize("wanted", ["acme", "acme-config", "acme-python"])
def test_resolve_pair(oracles: list[Oracle], wanted: str) -> None:
    pair = resolve_pair(oracles, wanted)
    assert (pair.config.name, pair.sdk.name) == ("acme-config", "acme-python")
    assert (pair.language, pair.paired) == ("python", "proven")
    assert resolve_pair(oracles, wanted, language="python") == pair


def test_resolve_pair_unknown() -> None:
    with pytest.raises(HarnessError, match="FER4020"):
        resolve_pair(ORACLES, "lone-config")


@pytest.mark.parametrize("wanted", ["acme", "acme-config", "acme-typescript"])
def test_resolve_pair_by_language(wanted: str) -> None:
    pair = resolve_pair(MULTI, wanted, language="typescript")
    assert (pair.config.name, pair.sdk.name) == ("acme-config", "acme-typescript")
    assert (pair.language, pair.paired) == ("typescript", "nearest")


def test_resolve_pair_language_from_sdk_name() -> None:
    pair = resolve_pair(MULTI, "acme-go")
    assert (pair.sdk.name, pair.language, pair.paired) == ("acme-go", "go", "proven")


def test_resolve_pair_config_without_a_python_sdk() -> None:
    # A second config of the group, generated only for C#: the group stays the Python pair.
    oracles = [
        *MULTI,
        oracle("acme-csharp-config", "config", None),
        oracle("acme-csharp", "sdk", "acme-csharp-config", "csharp", "proven"),
    ]
    assert resolve_pair(oracles, "acme").config.name == "acme-config"
    for wanted in ("acme", "acme-csharp-config", "acme-csharp"):
        pair = resolve_pair(oracles, wanted, language="csharp")
        assert (pair.config.name, pair.sdk.name, pair.paired) == (
            "acme-csharp-config",
            "acme-csharp",
            "proven",
        )
    with pytest.raises(HarnessError, match="FER4020"):
        resolve_pair(oracles, "acme-csharp-config")


def test_resolve_pair_language_mismatch() -> None:
    with pytest.raises(HarnessError, match="FER4020 acme: no config oracle with a paired ruby"):
        resolve_pair(MULTI, "acme", language="ruby")
    with pytest.raises(HarnessError, match="FER4020"):
        resolve_pair(MULTI, "acme-go", language="typescript")
    with pytest.raises(HarnessError, match="FER4020"):
        resolve_pair(ORACLES, "acme", language="go")


def test_lock_requirements() -> None:
    lock = """# generated by rye
-e file:.
anyio==4.12.1
    # via httpx
Acme_SDK==1.0.0
pydantic[email]==2.12.0 ; python_version >= "3.9"
anyio==4.12.1
git+https://example.com/x.git
"""
    assert lock_requirements(lock, exclude=["acme-sdk"]) == [
        "anyio==4.12.1",
        "pydantic[email]==2.12.0",
    ]


def test_mock_command() -> None:
    steady = mock_command("npm exec --package=@stdy/cli@0.22.1 -- steady", Path("s.yml"))
    assert steady[3] == "--package=@stdy/cli@0.22.1"
    assert steady[-1] == "s.yml"
    prism = mock_command("prism mock", Path("s.yml"), port=5000)
    assert "@stoplight/prism-cli" in prism[3]
    assert prism[-3:] == ("-p", "5000", "s.yml")


def test_parse_junit() -> None:
    xml = """<testsuites><testsuite>
<testcase name="a"/><testcase name="b"><failure/></testcase>
<testcase name="c"><error/></testcase><testcase name="d"><skipped/></testcase>
<testcase name="e"/></testsuite></testsuites>"""
    counts = parse_junit(xml)
    assert counts == Outcomes(passed=2, failed=1, errors=1, skipped=1)
    assert counts.as_dict()["total"] == 5


