from pathlib import Path

import pytest

from oracles.fetch import Oracle
from scripts.parity.harness import (
    HarnessError,
    Outcomes,
    breakage_kinds,
    lock_requirements,
    mock_command,
    parse_junit,
    resolve_pair,
)


def oracle(name: str, kind: str, pairs_with: str | None) -> Oracle:
    return Oracle(name, "acme", kind, "a/b", "https://x", "0" * 40, "", None, {}, pairs_with)


ORACLES = [
    oracle("acme-python", "sdk", "acme-config"),
    oracle("acme-config", "config", "acme-python"),
    oracle("lone-config", "config", None),
]


@pytest.mark.parametrize("wanted", ["acme", "acme-config", "acme-python"])
def test_resolve_pair(wanted: str) -> None:
    pair = resolve_pair(ORACLES, wanted)
    assert (pair.config.name, pair.sdk.name) == ("acme-config", "acme-python")


def test_resolve_pair_unknown() -> None:
    with pytest.raises(HarnessError, match="FER4020"):
        resolve_pair(ORACLES, "lone-config")


def test_lock_requirements() -> None:
    lock = """# generated by rye
-e file:.
anyio==4.12.1
    # via httpx
Acme_SDK==1.0.0
pydantic[email]==2.12.0 ; python_version >= "3.9"
anyio==4.12.1
git+https://example.com/x.git
"""
    assert lock_requirements(lock, exclude=["acme-sdk"]) == [
        "anyio==4.12.1",
        "pydantic[email]==2.12.0",
    ]


def test_mock_command() -> None:
    steady = mock_command("npm exec --package=@stdy/cli@0.22.1 -- steady", Path("s.yml"))
    assert steady[3] == "--package=@stdy/cli@0.22.1"
    assert steady[-1] == "s.yml"
    prism = mock_command("prism mock", Path("s.yml"), port=5000)
    assert "@stoplight/prism-cli" in prism[3]
    assert prism[-3:] == ("-p", "5000", "s.yml")


def test_parse_junit() -> None:
    xml = """<testsuites><testsuite>
<testcase name="a"/><testcase name="b"><failure/></testcase>
<testcase name="c"><error/></testcase><testcase name="d"><skipped/></testcase>
<testcase name="e"/></testsuite></testsuites>"""
    counts = parse_junit(xml)
    assert counts == Outcomes(passed=2, failed=1, errors=1, skipped=1)
    assert counts.as_dict()["total"] == 5


def test_breakage_kinds() -> None:
    assert breakage_kinds(["B", "A", "B"]) == {"A": 1, "B": 2}
