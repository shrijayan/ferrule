/// `Cargo.toml`.
#[must_use]
pub fn cargo_toml(g: &Gen<'_>) -> String {
    let n = &g.names;
    let mut out = format!(
        "[package]\nname = \"{}\"\nversion = \"{}\"\nedition = \"2024\"\nrust-version = \"1.88\"\ndescription = {:?}\n",
        n.crate_name,
        n.version,
        description(g)
    );
    if let Some(license) = &n.license {
        let _ = writeln!(out, "license = {license:?}");
    }
    if let Some(repo) = &n.repository {
        let _ = writeln!(out, "repository = \"https://github.com/{repo}\"");
    }
    out.push_str("readme = \"README.md\"\n\n[features]\n# A client whose calls block, on a runtime of its own.\nblocking = []\n# A fake server that answers like the API, for tests.\ntesting = []\n\n");
    out.push_str(DEPENDENCIES);
    out
}

/// One line about the API: the first line of the spec's description.
fn description(g: &Gen<'_>) -> String {
    let title = g.client.description.lines().next().unwrap_or_default().trim();
    if title.is_empty() {
        format!("Rust SDK for the {} API", g.names.client)
    } else {
        format!("Rust SDK for the {title} API")
    }
}

/// `rustfmt.toml`: the layout the generated code is formatted with.
#[must_use]
pub fn rustfmt_toml() -> String {
    "edition = \"2024\"\nstyle_edition = \"2024\"\n".to_owned()
}

/// The first test case, for the README's example.
fn first_case(tests: &[ResourceTests]) -> Option<&TestCase> {
    tests.iter().find_map(|t| {
        t.cases
            .iter()
            .find(|c| !c.deprecated)
            .or_else(|| first_case(&t.children))
    })
}

/// `README.md`, which is also the crate's documentation (its examples compile as doctests).
#[must_use]
pub fn readme(g: &Gen<'_>, tests: &[ResourceTests], examples: &Examples, options: &[(String, String)]) -> String {
    let n = &g.names;
    let client = &n.client;
    let mut out = format!("# {}\n\n{}.\n\n", n.crate_name, description(g));
    let _ = write!(
        out,
        "Generated by Ferrule from the API's OpenAPI spec and `stainless.yml`.\n\n## Install\n\n```toml\n[dependencies]\n{} = \"{}\"\n```\n\nThe `blocking` feature adds a client whose calls block; `testing` adds a fake server.\n\n## Usage\n\n",
        n.crate_name, n.version
    );
    let builder = builder_calls(options);
    if let Some(case) = first_case(tests) {
        let call = examples.resolve(&case.call, &n.lib);
        let (send, show) = match case.kind {
            CallKind::Plain => (".await?", "println!(\"{response:?}\");"),
            CallKind::Page => (".await?", "println!(\"{:?}\", response.items);"),
            CallKind::Stream => (".stream().await?", "let _events = response;"),
        };
        let _ = write!(
            out,
            "```rust,no_run\nuse {lib}::{client};\n\n#[tokio::main]\nasync fn main() -> Result<(), {lib}::Error> {{\n    let client = {client}::builder(){builder}\n        .build()?;\n    let response = client.{call}{send};\n    {show}\n    Ok(())\n}}\n```\n\n",
            lib = n.lib
        );
    }
    let _ = write!(
        out,
        "Each option the builder does not set is read from the environment, so `{client}::new()` works\nwhen the environment has them.\n\n## Requests\n\nA method takes its required params as arguments and returns a request: set its optional params,\nthen `.await` it (or call `send()`). `request_timeout`, `request_max_retries`, `extra_header` and\n`extra_query` change one request.\n\nList methods return a `Page`; `paginate()` gives a `Stream` of every item of every page.\nStreaming methods return a `Stream` of events.\n\n## Errors\n\nEvery call returns `Result<T, {lib}::Error>`. A status that is not 2xx gives the variant of its\nstatus (`NotFound`, `RateLimit`, …) with the status, headers and body; `Connection`, `Timeout` and\n`Decode` say why no response could be read.\n\n## Retries and timeouts\n\nConnection errors, timeouts, 408, 409, 429 and 5xx responses are retried with exponential backoff,\n{retries} times by default (`max_retries`). A request times out after {timeout} seconds by default\n(`timeout`).\n\n## Blocking client\n\nWith the `blocking` feature, `{client}Builder::build_blocking()` gives `{lib}::blocking::{client}`,\nwhose requests block on `send()`.\n",
        lib = n.lib,
        retries = g.client.settings.as_ref().map_or(2, |s| s.max_retries),
        timeout = g.client.settings.as_ref().map_or(60.0, |s| s.timeout_seconds),
    );
    out
}

/// `\n        .option(value)` for each required client option.
fn builder_calls(options: &[(String, String)]) -> String {
    options.iter().fold(String::new(), |mut out, (k, v)| {
        let _ = write!(out, "\n        .{k}({v})");
        out
    })
}

/// `src/lib.rs`.
#[must_use]
pub fn lib_rs(g: &Gen<'_>, top: &[(String, String)], pages: bool) -> String {
    let client = &g.names.client;
    let mut out = String::from("#![doc = include_str!(\"../README.md\")]\n\n");
    for (module, doc) in top {
        out.push_str(doc);
        let _ = writeln!(out, "pub mod {module};");
    }
    out.push_str("/// The client and its builder.\npub mod client;\n");
    if pages {
        out.push_str("/// The API's pagination schemes.\npub mod pages;\n");
    }
    out.push_str(
        "/// The runtime the generated code is built on.\npub mod rt;\n\n#[cfg(feature = \"blocking\")]\npub mod blocking;\n#[cfg(any(test, feature = \"testing\"))]\npub mod testing;\n\n",
    );
    let environment = if g.client.settings.as_ref().is_some_and(|s| !s.environments.is_empty()) {
        "Environment, "
    } else {
        ""
    };
    let _ = writeln!(out, "pub use client::{{{environment}{client}, {client}Builder}};");
    out.push_str("pub use rt::{ApiError, Error, EventStream, Page, PageStream, Request, RequestOptions, Result};\n");
    out
}

/// `src/testing/routes.rs`.
#[must_use]
pub fn routes(routes: &[Route]) -> String {
    let streams = routes.iter().any(|r| r.streaming.is_some());
    let mut out = format!(
        "//! Every operation of the API, with the reply the fake server gives it.\n\nuse super::{};\n\n/// The API's routes.\npub static ROUTES: &[Route] = &[\n",
        if streams { "{Route, StreamReply}" } else { "Route" }
    );
    for r in routes {
        let streaming = r.streaming.as_ref().map_or_else(
            || "None".to_owned(),
            |(param, content_type, body)| {
                format!(
                    "Some(StreamReply {{ param: {param:?}, content_type: {content_type:?}, body: {} }})",
                    raw(body)
                )
            },
        );
        let _ = writeln!(
            out,
            "    Route {{\n        method: {:?},\n        path: {:?},\n        status: {},\n        content_type: {:?},\n        body: {},\n        streaming: {streaming},\n    }},",
            r.method,
            r.path,
            r.status,
            r.content_type,
            raw(&r.body)
        );
    }
    out.push_str("];\n");
    out
}

/// `text` as a raw string literal, with as many `#` as it needs.
fn raw(text: &str) -> String {
    let hashes = "#".repeat(
        (1..64)
            .find(|n| !text.contains(&format!("\"{}", "#".repeat(*n))))
            .unwrap_or(1),
    );
    format!("r{hashes}\"{text}\"{hashes}")
}

/// `tests/api.rs`: every call against the fake server.
#[must_use]
pub fn api_tests(
    g: &Gen<'_>,
    client_tests: &[TestCase],
    tests: &[ResourceTests],
    examples: &Examples,
    options: &[(String, String)],
) -> String {
    let n = &g.names;
    let client = &n.client;
    let builder = builder_calls(options);
    let uses_streams = has_kind(client_tests, tests, CallKind::Page) || has_kind(client_tests, tests, CallKind::Stream);
    let stream_ext = if uses_streams {
        "use futures_util::StreamExt;\n"
    } else {
        ""
    };
    let mut out = format!(
        "//! Every method of the API, called against the fake server (`testing` feature).\n#![cfg(feature = \"testing\")]\n\n{stream_ext}use {lib}::testing::FakeServer;\nuse {lib}::{client};\n\nfn client(server: &FakeServer) -> {client} {{\n    {client}::builder(){builder}\n        .base_url(server.base_url())\n        .max_retries(0)\n        .build()\n        .expect(\"a client\")\n}}\n",
        lib = n.lib
    );
    for case in client_tests {
        out.push('\n');
        out.push_str(&test_fn(case, examples, &n.lib, ""));
    }
    for t in tests {
        out.push('\n');
        out.push_str(&test_module(t, examples, &n.lib, ""));
    }
    let blocking = [CallKind::Plain, CallKind::Page, CallKind::Stream]
        .into_iter()
        .filter_map(|kind| first_of(client_tests, tests, kind))
        .map(|case| {
            let call = examples.resolve(&case.call, &n.lib);
            match case.kind {
                CallKind::Plain => format!(
                    "    let response = client.{call}.send();\n    assert!(response.is_ok(), \"{{response:?}}\");\n"
                ),
                CallKind::Page => format!(
                    "    let items: Vec<_> = client.{call}.paginate().collect();\n    assert!(items.iter().all(Result::is_ok), \"{{items:?}}\");\n"
                ),
                CallKind::Stream => format!(
                    "    let events: Vec<_> = client.{call}.stream().expect(\"a stream\").collect();\n    assert!(events.iter().all(Result::is_ok), \"{{events:?}}\");\n"
                ),
            }
        })
        .collect::<Vec<_>>();
    if !blocking.is_empty() {
        let _ = write!(
            out,
            "\n#[cfg(feature = \"blocking\")]\n#[test]\nfn blocking_client() {{\n    let server = FakeServer::start();\n    let client = {lib}::blocking::{client}::from_async(client(&server)).expect(\"a blocking client\");\n{}    assert_eq!(server.requests().len(), {});\n}}\n",
            blocking.concat(),
            blocking.len(),
            lib = n.lib
        );
    }
    out
}

/// The first test case of `kind` whose method is not deprecated.
fn first_of<'t>(client_tests: &'t [TestCase], tests: &'t [ResourceTests], kind: CallKind) -> Option<&'t TestCase> {
    let usable = |c: &&TestCase| c.kind == kind && !c.deprecated;
    client_tests
        .iter()
        .find(usable)
        .or_else(|| tests.iter().find_map(|t| first_of(&t.cases, &t.children, kind)))
}

fn has_kind(client_tests: &[TestCase], tests: &[ResourceTests], kind: CallKind) -> bool {
    client_tests.iter().any(|c| c.kind == kind) || tests.iter().any(|t| has_kind(&t.cases, &t.children, kind))
}

fn test_module(t: &ResourceTests, examples: &Examples, lib: &str, indent: &str) -> String {
    let inner = format!("{indent}    ");
    let mut body = String::new();
    let mut first = true;
    for case in &t.cases {
        if !first {
            body.push('\n');
        }
        first = false;
        body.push_str(&test_fn(case, examples, lib, &inner));
    }
    for child in &t.children {
        if !first {
            body.push('\n');
        }
        first = false;
        body.push_str(&test_module(child, examples, lib, &inner));
    }
    format!("{indent}mod {} {{\n{inner}use super::*;\n\n{body}{indent}}}\n", t.name)
}

fn test_fn(case: &TestCase, examples: &Examples, lib: &str, indent: &str) -> String {
    let call = examples.resolve(&case.call, lib);
    let allow = if case.deprecated {
        format!("{indent}#[allow(deprecated)]\n")
    } else {
        String::new()
    };
    let body = match case.kind {
        CallKind::Plain => format!(
            "{indent}    let response = client.{call}.await;\n{indent}    assert!(response.is_ok(), \"{{response:?}}\");\n"
        ),
        CallKind::Page => format!(
            "{indent}    let page = client.{call}.await;\n{indent}    assert!(page.is_ok(), \"{{page:?}}\");\n{indent}    let items: Vec<_> = client.{call}.paginate().collect().await;\n{indent}    assert!(items.iter().all(Result::is_ok), \"{{items:?}}\");\n"
        ),
        CallKind::Stream => format!(
            "{indent}    let events = client.{call}.stream().await;\n{indent}    let events: Vec<_> = events.expect(\"a stream\").collect().await;\n{indent}    assert!(events.iter().all(Result::is_ok), \"{{events:?}}\");\n"
        ),
    };
    let path = case.path.as_ref().map_or_else(String::new, |p| {
        format!("{indent}    assert_eq!(request.path, {p:?});\n")
    });
    format!(
        "{allow}{indent}#[tokio::test]\n{indent}async fn {}() {{\n{indent}    let server = FakeServer::start();\n{indent}    let client = client(&server);\n{body}{indent}    let request = &server.requests()[0];\n{indent}    assert_eq!(request.method, {:?});\n{path}{indent}}}\n",
        case.name.trim_start_matches("r#"),
        case.http_method
    )
}
