/// `test_hardcoded_query_params_in_url`, which the older generator of lumaai's tests lacks.
fn hardcoded_query_test(asynchronous: bool) -> String {
    let (def, client, ty) = if asynchronous {
        ("async def", "async_client", "AsyncLumaAI")
    } else {
        ("def", "client", "LumaAI")
    };
    format!(
        "    {def} test_hardcoded_query_params_in_url(self, {client}: {ty}) -> None:
        request = {client}._build_request(FinalRequestOptions(method=\"get\", url=\"/foo?beta=true\"))
        url = httpx.URL(request.url)
        assert dict(url.params) == {{\"beta\": \"true\"}}

        request = {client}._build_request(
            FinalRequestOptions(
                method=\"get\",
                url=\"/foo?beta=true\",
                params={{\"limit\": \"10\", \"page\": \"abc\"}},
            )
        )
        url = httpx.URL(request.url)
        assert dict(url.params) == {{\"beta\": \"true\", \"limit\": \"10\", \"page\": \"abc\"}}

        request = {client}._build_request(
            FinalRequestOptions(
                method=\"get\",
                url=\"/files/a%2Fb?beta=true\",
                params={{\"limit\": \"10\"}},
            )
        )
        assert request.url.raw_path == b\"/files/a%2Fb?beta=true&limit=10\"

"
    )
}

