/// One config oracle and every way Ferrule's files differ from it.
struct Oracle {
    name: &'static str,
    sdk: &'static str,
    /// (file, oracle text, Ferrule text), applied to the oracle text before comparing; each must
    /// occur in it.
    known: Vec<(&'static str, String, String)>,
    /// README.md sections (`## ` headings) Ferrule does not write, removed from the oracle text up
    /// to the next `## ` heading; each must occur in it.
    dropped_sections: &'static [&'static str],
    /// Files not compared, with the reason.
    skipped: &'static [(&'static str, &'static str)],
    /// Retry-probe arguments whose value the model cannot give yet ([`API_TEST_EXAMPLES`]):
    /// (argument, the oracle's value).
    probe_examples: &'static [(&'static str, &'static str)],
    /// The fixture keeps only the README example's endpoint, so the files listing every
    /// endpoint (api.md, `.stats.yml`, `tests/api_resources/`) are not compared.
    reduced: bool,
    /// When set, the only files compared, with the reason the others are not.
    only: Option<(&'static [&'static str], &'static str)>,
}

