//! The project files of the config oracles whose credentials OneBusAway's do not cover, emitted
//! through the real path (annotated spec -> model -> `to_project_files_input`) and compared with
//! the pinned oracle SDK byte for byte, after the branding substitutions of
//! `src/emit/files/BRANDING.md` and the differences listed per oracle below:
//!
//! - lumaai: a bearer token `auth_token` read from `LUMAAI_API_KEY`;
//! - isaacus: a bearer `api_key`, without a mock server (`disable_mock_tests`);
//! - imagekit: HTTP basic auth from two options, `private_key` and `password` (with a default).
//!
//! `tests/project_files/<name>/annotated.json` is `ferrule-gen convert` of the config oracle
//! (`README.md` there says which commit, and how lumaai's and imagekit's were reduced); `meta.json`
//! holds what `x-ferrule-config` does not carry yet ([`ProjectMeta`]), each value read from the
//! config or the oracle. Skipped when the oracle isn't fetched.

